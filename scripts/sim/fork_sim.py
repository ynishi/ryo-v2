"""Monte Carlo of one Issue on a ryo-rs-sized workspace (227k lines, 504 files; ryo-rs is a
verification repository used as a large sample).

The simulation behind the scales CONCEPT.md marks as hypotheses (forks, results, time).
usage: python3 -I scripts/sim/fork_sim.py; the sensitivity table: python3 -I scripts/sim/sens.py

Modes:
  M0  one session, every check re-applies the whole path from base (the current code)
  M1  one session, writes stack on top (fork -> write -> write -> read), one branch at a time
  M2  stacked writes plus c concurrent OS-level CoW forks sharing 16 cores

Anchors (measured, SEARCH_LEDGER sections "Bench" and "ryo-rs (large run)"):
  full cold diagnosis of 504 files 35 s; small edit in a widely used crate 1.2-2.1 s;
  leaf crate (41 files) 0.31-0.41 s; revert 0.04-0.36 s; outer cargo check ~21 s per candidate.
Everything else is an estimate and is a parameter here.
"""
import math
import random
import statistics as st

T_FULL = 35.0      # s, full diagnosis of the workspace (measured, cold)
T_FIXED = 0.4      # s, fixed cost of one check (leaf crate measurement)
CORES = 16


def ln(med, sigma):
    return med * math.exp(random.gauss(0.0, sigma))


SCENARIOS = {
    # f_big: share of the workspace's analysis a change invalidates (calibrated: 0.03 -> 1.45 s,
    # the measured small edit in a widely used crate). ai_lines: lines the AI writes itself; the
    # rest of the change is generated by the engine from refactor calls (signature threading,
    # renames, moves). steps: refactor calls per variant, each realised on the state the previous
    # one left. p0: share of AI variants that pass the first check. cargo: one cargo check of the
    # change, for the agent loop without ryo.
    "S1 bug fix, 2 files, ~100 lines": dict(f_big=0.03, ai_lines=80, steps=1, p0=0.5, cargo=21.0),
    "S2 feature, 1% files, ~2k lines": dict(f_big=0.10, ai_lines=400, steps=3, p0=0.3, cargo=30.0),
    "S3 cross-cutting, 5% files, ~10k lines": dict(f_big=0.30, ai_lines=600, steps=6, p0=0.15, cargo=60.0),
}

COMMON = dict(
    k=6,            # AI variants per Issue (parallel calls)
    q=0.5,          # chance one repair round makes a failing variant pass
    max_rep=3,      # repair rounds per variant
    m_polish=10,    # refactor deltas verified on top of each passing variant
    p_polish=0.6,   # share of those that pass
    goal=10,        # passed alternatives to hand over
    deadline=60.0,  # s from the Issue
    l_plan=8.0,     # s, Issue -> Request and plan (AI)
    l_repair=5.0,   # s, one repair (AI)
    l_judge=2.0,    # s, priors for the polish proposals (AI)
    tok_line=12, tok_s=300.0, gen_over=2.0,  # AI writing speed
    f_delta=0.015,  # share a small delta on top invalidates
    revert_frac=0.15, step_real=0.3, expand=1.0, fork_cost=0.05,
)


def t_check16(f):
    return T_FIXED + T_FULL * f


def amdahl_ratio(c, a):
    """Wall time of one check when c checks share the cores, relative to one check alone."""
    p = CORES / c
    return ((1 - a) + a / p) / ((1 - a) + a / CORES)


def trial(sc, mode, c=1, a=0.7, cm=COMMON):
    """Returns (time_to_goal or None, passed_by_deadline, time_first_pass or None)."""
    stacked = mode in ("M1", "M2")
    slots = [0.0] * (c if mode == "M2" else 1)
    ratio = amdahl_ratio(c, a) if mode == "M2" else 1.0
    t0 = ln(cm["l_plan"], 0.3)
    variants = []
    for _ in range(cm["k"]):
        gen = sc["ai_lines"] * cm["tok_line"] / cm["tok_s"] + cm["gen_over"]
        variants.append(dict(ready=t0 + ln(gen, 0.25), tbig=ln(t_check16(sc["f_big"]), 0.3)))
    # job = (ready_time, variant index, kind, extra)
    jobs = []
    for i, v in enumerate(variants):
        jobs.append([v["ready"], i, "initial", 0])
    passes = []
    order = sorted(range(len(variants)), key=lambda i: variants[i]["ready"])
    current = order[0] if mode == "M1" else None
    done_variants = set()

    while jobs and len(passes) < cm["goal"]:
        if mode == "M1":
            # One branch at a time; its AI waits are dead time for the only session.
            elig = [j for j in jobs if j[1] == current]
            if not elig:
                done_variants.add(current)
                rest = [i for i in order if i not in done_variants]
                if not rest:
                    break
                slots[0] += cm["revert_frac"] * variants[current]["tbig"]  # revert the old branch
                current = rest[0]
                continue
        else:
            elig = jobs
        job = min(elig, key=lambda j: j[0])
        jobs.remove(job)
        ready, i, kind, extra = job
        v = variants[i]
        s = min(range(len(slots)), key=lambda x: slots[x])
        start = max(slots[s], ready)
        tbig = v["tbig"]
        td = ln(t_check16(cm["f_delta"]), 0.4)
        if kind == "initial":
            real = sc["steps"] * cm["step_real"]
            if not stacked:
                real += tbig * (sc["steps"] + 1) / 2  # each step needs the earlier ones applied again
            cost = real + tbig * ratio + (cm["fork_cost"] if mode == "M2" else 0.0)
            end = start + cost
            if not stacked:
                end += cm["revert_frac"] * tbig
            slots[s] = end
            if random.random() < sc["p0"]:
                passes.append(end)
                jobs.append([end + cm["l_judge"], i, "expand", 0])
            else:
                jobs.append([end + ln(cm["l_repair"], 0.3), i, "repair", 1])
        elif kind == "repair":
            cost = (tbig * 1.0 if not stacked else td) * ratio
            end = start + cost + (cm["revert_frac"] * tbig if not stacked else 0.1)
            slots[s] = end
            if random.random() < cm["q"]:
                passes.append(end)
                jobs.append([end + cm["l_judge"], i, "expand", 0])
            elif extra < cm["max_rep"]:
                jobs.append([end + ln(cm["l_repair"], 0.3), i, "repair", extra + 1])
        elif kind == "expand":
            # the expansion reads the variant's state; without stacking it must be applied again
            end = start + (cm["expand"] + (0.0 if stacked else tbig)) * ratio
            slots[s] = end
            for _ in range(cm["m_polish"]):
                jobs.append([end, i, "polish", 0])
        elif kind == "polish":
            cost = ((tbig + td) if not stacked else td) * ratio
            end = start + cost + (cm["revert_frac"] * tbig if not stacked else 0.1)
            slots[s] = end
            if random.random() < cm["p_polish"]:
                passes.append(end)
    passes.sort()
    goal_t = passes[cm["goal"] - 1] if len(passes) >= cm["goal"] else None
    by_dl = sum(1 for t in passes if t <= cm["deadline"])
    first = passes[0] if passes else None
    return goal_t, by_dl, first


def agent_trial(sc, cm=COMMON):
    """An AI agent without ryo: one variant at a time, each check is a cargo check."""
    t = ln(cm["l_plan"], 0.3)
    gen = sc["ai_lines"] * cm["tok_line"] / cm["tok_s"] + cm["gen_over"]
    for _ in range(cm["k"]):
        t += ln(gen, 0.25)
        t += ln(sc["cargo"], 0.3)
        if random.random() < sc["p0"]:
            return t
        for _r in range(cm["max_rep"]):
            t += ln(cm["l_repair"], 0.3) + ln(sc["cargo"], 0.3)
            if random.random() < cm["q"]:
                return t
    return None


def summarise(rows, deadline=60.0):
    goals = [g for g, _, _ in rows if g is not None]
    firsts = [f for _, _, f in rows if f is not None]
    n = len(rows)
    return dict(
        p_goal_60=sum(1 for g, _, _ in rows if g is not None and g <= deadline) / n,
        med_goal=st.median(goals) if goals else float("nan"),
        p_first_60=sum(1 for f in firsts if f <= deadline) / n,
        med_first=st.median(firsts) if firsts else float("nan"),
        mean_passed_60=sum(b for _, b, _ in rows) / n,
    )


def main():
    random.seed(20261101)
    n = 3000
    modes = [("M0 from base", "M0", 1, 0.7), ("M1 stacked, 1 branch", "M1", 1, 0.7)]
    for c in (4, 8, 16):
        for a in (0.5, 0.7, 0.9):
            modes.append((f"M2 stacked + {c} forks (a={a})", "M2", c, a))
    for name, sc in SCENARIOS.items():
        print(f"\n## {name}  (big check {t_check16(sc['f_big']):.1f} s at 16 threads, p0={sc['p0']})")
        print("| mode | P(10 passed <= 60 s) | median time to 10 | P(first passed <= 60 s) | median first | mean passed by 60 s |")
        print("|---|---|---|---|---|---|")
        for label, mode, c, a in modes:
            rows = [trial(sc, mode, c, a) for _ in range(n)]
            s = summarise(rows)
            print(f"| {label} | {s['p_goal_60']:.2f} | {s['med_goal']:.0f} s | {s['p_first_60']:.2f} | {s['med_first']:.0f} s | {s['mean_passed_60']:.1f} |")
        ag = [agent_trial(sc) for _ in range(n)]
        okf = [x for x in ag if x is not None]
        print(f"| agent + cargo check (no ryo) | - | - | {sum(1 for x in okf if x <= 60)/n:.2f} | {st.median(okf):.0f} s | {sum(1 for x in okf if x <= 60)/n:.1f} |")

    # The question asked: 200 deltas on top of one big change (S3), how long to verify them all?
    print("\n## 200 deltas on top of one S3 change (deterministic, medians)")
    tbig = t_check16(0.30)
    td = t_check16(COMMON["f_delta"])
    print("| way | time |\n|---|---|")
    print(f"| 1-step fork x 200 (re-apply the big change each time) | {200 * (tbig + td + 0.15 * tbig):.0f} s |")
    print(f"| stacked, 1 branch (write the big change once, 200 deltas on top) | {tbig + 200 * (td + 0.1):.0f} s |")
    for a in (0.5, 0.7, 0.9):
        for c in (16, 200):
            if c * 0.2 + 5.5 + 1.5 > 30 - 4:
                print(f"| {c} concurrent forks (a={a}) | does not fit in 30 GiB at 0.2 GB per fork |")
                continue
            waves = math.ceil(200 / c)
            print(f"| {c} concurrent forks (a={a}) | {tbig + waves * td * amdahl_ratio(c, a) + 0.05:.0f} s |")


if __name__ == "__main__":
    main()
